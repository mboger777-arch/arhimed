// перечень всех вариантов: [кто, имя, аргументы]
function VL_ALL() {
  const out = [], add = (who, k, ...a) => { const [t, s] = VLDEF[k](...a); out.push({ who, k, a, t, s }); };
  const R = (a, b) => { const r = []; for (let i = a; i <= b; i++) r.push(i); return r; };
  add('ded', 'l1Start'); add('ded', 'l1All'); R(0, 9).forEach(n => add('ded', 'l1Gate', n));
  add('ded', 'l2Start'); add('ded', 'wind'); add('ded', 'l2MinusH1'); add('ded', 'l2PlusH1'); add('ded', 'l2PlusOk');
  add('ded', 'countLit'); add('ded', 'countOut'); add('ded', 'tryYou'); add('bublik', 'tryYou');
  R(1, 9).forEach(K => { add('ded', 'l2MinusQ', K); add('ded', 'l2MinusH2', K); add('ded', 'l2MinusOk', 10 - K); add('ded', 'l2PlusQ', 10 - K); add('ded', 'toTen', 10 - K); add('bublik', 'toTen', 10 - K); });
  for (const a of R(2, 5)) for (const b of R(1, Math.min(4, 8 - a))) {
    add('bublik', 'l3Start', a, b); add('bublik', 'l3Sum', a, b);
    R(0, a + b - 1).forEach(k => add('bublik', 'l3NotYet', k, a, b));
    for (const c of R(1, Math.min(4, a + b - 1))) { add('bublik', 'l3Q', a + b, c); add('bublik', 'l3H2', a + b, c); add('bublik', 'l3Ok', a + b - c); }
  }
  add('bublik', 'l3Wait'); add('bublik', 'firstBuns'); add('bublik', 'firstAnswer'); add('bublik', 'l3Shchelk'); add('shchelk', 'shTook'); add('bublik', 'l3H1'); add('bublik', 'l3Count');
  add('bublik', 'bkStart'); add('bublik', 'bkH1'); add('bublik', 'bkCountEmpty'); add('bublik', 'bkFull'); add('bublik', 'bkH2a'); add('bublik', 'bkCountAll');
  add('bublik', 'bkH3a'); add('bublik', 'bkCountSugar'); add('bublik', 'bkFlag'); add('shchelk', 'shTease');
  R(3, 7).forEach(N => { add('bublik', 'bkQ1', N); add('bublik', 'bkOk1', N); add('bublik', 'toTen', N); });
  R(1, 7).forEach(k => add('bublik', 'bkCollect', k));
  R(2, 8).forEach(x => { add('bublik', 'bkQ3', x); add('bublik', 'bkH3b', x); add('bublik', 'bkOk3', x); });
  for (const a of R(2, 6)) for (const b of R(1, Math.min(4, 9 - a))) { add('bublik', 'bkQ2', a, b); add('bublik', 'addMore', a, b); add('bublik', 'bkOk2', a, b); }
  for (const a of R(1, 9)) for (const b of R(1, 10 - a)) { add('ded', 'addMore', a, b); add('ded', 'l5Q', a, '+', b); add('ded', 'l5HPlus2', a, b); }
  for (const a of R(2, 10)) for (const b of R(1, a - 1)) { add('ded', 'l5Q', a, '−', b); add('ded', 'l5HMinus1', a, b); add('ded', 'l5HMinus2', a, b); }
  add('ded', 'l5Start'); R(0, 4).forEach(i => add('ded', 'l5Ok', i)); add('ded', 'l5Lift');
  const seen = new Set();
  return out.filter(o => { const key = o.who + '|' + o.t; if (seen.has(key)) return false; seen.add(key); return true; });
}
if (typeof module !== 'undefined') module.exports = { VL_ALL, VLDEF, RU };
