function VL_ALL() {
  const out = [], seen = new Set();
  for (const k in VLDEF) { const [who, t, s] = VLDEF[k]; const key = who + '|' + t; if (seen.has(key)) continue; seen.add(key); out.push({ who, k, a: [], t, s: s || t }); }
  return out;
}
